def main() -> None:
    db = DatabaseManager()
    cursor = db.conn.cursor()
    try:
        voice = load_content_voice_context(
            cursor,
            user_id=OWNER_ID,
            business_id=BUSINESS_ID,
            limit=5,
        )
        cursor.execute(
            """
            SELECT id, scheduled_for, metadata_json
            FROM contentplanitems
            WHERE plan_id = %s
            ORDER BY scheduled_for, id
            """,
            (PLAN_ID,),
        )
        rows = cursor.fetchall() or []
        if len(rows) != len(VARIANTS):
            raise RuntimeError(f"Expected {len(VARIANTS)} items, got {len(rows)}")
        results = []
        for row in rows:
            row_value = dict(row) if isinstance(row, dict) else {}
            item_id = str(row_value.get("id") or "")
            scheduled_for = str(row_value.get("scheduled_for") or "")
            metadata = row_value.get("metadata_json") or {}
            if not isinstance(metadata, dict):
                metadata = json.loads(metadata or "{}")
            brief = metadata.get("content_brief_v1") or {}
            if not brief.get("complete"):
                raise RuntimeError(f"Incomplete brief for {item_id}")
            definitions = VARIANTS.get(scheduled_for) or []
            candidates = [
                {
                    "id": f"live-variant-{index}",
                    "angle": angle,
                    "text": text,
                    "used_fact_ids": ["event", "owner_detail", "owner_source"],
                    "unsupported_facts": [],
                }
                for index, (angle, text) in enumerate(definitions, start=1)
            ]
            scored = [_score_content_candidate(candidate, brief, voice) for candidate in candidates]
            failures = [
                candidate
                for candidate in scored
                if not candidate.get("quality_passed")
                or int(candidate.get("score") or 0) < 70
                or candidate.get("issues")
            ]
            distinct = {" ".join(str(item.get("text") or "").lower().split()) for item in scored}
            if len(scored) != 3 or len(distinct) != 3 or failures:
                raise RuntimeError(
                    json.dumps(
                        {
                            "item_id": item_id,
                            "scheduled_for": scheduled_for,
                            "failures": failures,
                            "variants": len(scored),
                            "distinct": len(distinct),
                        },
                        ensure_ascii=False,
                    )
                )
            selected = sorted(scored, key=lambda item: int(item.get("score") or 0), reverse=True)[0]
            generation = dict(metadata.get("content_generation_v2") or {})
            generation.update(
                {
                    "enabled": True,
                    "voice_profile_version": int(voice.get("version") or 1),
                    "selected_variant_id": str(selected.get("id") or ""),
                    "variants": scored,
                }
            )
            metadata.update(
                {
                    "generation_source": "editorial_grounded_live",
                    "generation_fallback_reason": "",
                    "quality_gate_version": "live_voice_v1",
                    "content_generation_v2": generation,
                }
            )
            cursor.execute(
                """
                UPDATE contentplanitems
                SET draft_text = %s,
                    status = 'draft_generated',
                    metadata_json = %s::jsonb,
                    updated_at = CURRENT_TIMESTAMP
                WHERE id = %s AND plan_id = %s
                """,
                (
                    str(selected.get("text") or ""),
                    json.dumps(metadata, ensure_ascii=False),
                    item_id,
                    PLAN_ID,
                ),
            )
            results.append(
                {
                    "scheduled_for": scheduled_for,
                    "item_id": item_id,
                    "selected": selected.get("id"),
                    "score": selected.get("score"),
                    "gates": {
                        "factual": selected.get("factual_gate_passed"),
                        "neuroslop": selected.get("neuroslop_passed"),
                        "editorial": selected.get("editorial_quality_passed"),
                        "voice": selected.get("voice_adherence_passed"),
                    },
                }
            )
        db.conn.commit()
        print(json.dumps({"success": True, "plan_id": PLAN_ID, "items": results}, ensure_ascii=False, indent=2))
    except Exception:
        db.conn.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    main()
