def _review_preview(review):
    comment = review.get("businessComment") if isinstance(review.get("businessComment"), dict) else {}
    return {
        "review_id": review.get("reviewId"),
        "rating": review.get("rating"),
        "review": review.get("text"),
        "reply_preview": comment.get("text"),
        "updated_at": review.get("updatedTime"),
    }


def _load_current_page(cursor):
    cursor.execute(
        """
        SELECT page_json, generated_json, published_json, edit_status
        FROM adminprospectingleadpublicoffers
        WHERE lead_id = %s AND slug = %s
        LIMIT 1
        """,
        (LEAD_ID, SLUG),
    )
    row = cursor.fetchone()
    if not row:
        raise RuntimeError("Public audit not found")
    return copy.deepcopy(row.get("published_json") or row.get("page_json") or row.get("generated_json") or {}), dict(row)


