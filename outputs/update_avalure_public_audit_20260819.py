def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    snapshot = json.loads(SNAPSHOT_PATH.read_text(encoding="utf-8"))

    conn = get_db_connection()
    try:
        cursor = conn.cursor(cursor_factory=RealDictCursor)
        page, old_row = build_page(cursor, snapshot)
        print(json.dumps({"slug": SLUG, "rating": page["rating"], "reviews_count": page["reviews_count"], "content_posts": len(page["content_audit"]["plan"])}, ensure_ascii=False, indent=2))
        if not args.apply:
            return

        if not BACKUP_PATH.exists():
            BACKUP_PATH.write_text(json.dumps(old_row, ensure_ascii=False, default=str, indent=2), encoding="utf-8")
        cursor.execute(
            """
            SELECT id FROM users
            WHERE COALESCE(is_superadmin, FALSE) = TRUE
            ORDER BY created_at ASC NULLS LAST, id ASC LIMIT 1
            """
        )
        user = cursor.fetchone()
        if not user:
            raise RuntimeError("Superadmin user not found")
        user_id = str(user["id"])
        cursor.execute(
            """
            UPDATE prospectingleads
            SET rating = 4.9,
                reviews_count = 31,
                reviews_json = %s,
                updated_at = NOW()
            WHERE id = %s
            """,
            (Json(snapshot.get("reviews") or []), LEAD_ID),
        )
        cursor.execute(
            """
            UPDATE adminprospectingleadpublicoffers
            SET page_json = %s,
                generated_json = %s,
                published_json = %s,
                edit_status = 'published',
                is_active = TRUE,
                published_by = %s,
                published_at = NOW(),
                updated_at = NOW()
            WHERE lead_id = %s AND slug = %s
            """,
            (Json(page), Json(page), Json(page), user_id, LEAD_ID, SLUG),
        )
        if cursor.rowcount != 1:
            raise RuntimeError("Public audit update did not affect exactly one row")
        conn.commit()
        print(f"Published: https://localos.pro/{SLUG}")
        print(f"Backup: {BACKUP_PATH}")
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


if __name__ == "__main__":
    main()
